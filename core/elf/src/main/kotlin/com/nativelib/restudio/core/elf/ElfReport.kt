package com.nativelib.restudio.core.elf

import com.nativelib.restudio.core.common.JsonWriter
import com.nativelib.restudio.core.common.toHexAddr

/** Deterministic TXT / JSON renderings of an [ElfFile]. Same input ⇒ byte-identical output. */
object ElfReport {

    fun toText(elf: ElfFile, title: String, sha256: String?): String = buildString {
        val h = elf.header
        val w = if (h.is64) 16 else 8
        appendLine("ELF ANALYSIS REPORT — $title")
        appendLine("Generated by Native Library RE Studio (static analysis; nothing was executed)")
        sha256?.let { appendLine("SHA-256: $it") }
        appendLine("File size: ${elf.fileSize} bytes")
        appendLine()
        appendLine("== ELF HEADER ==")
        appendLine("Class:        ELF${h.ident.elfClass.bits}")
        appendLine("Endianness:   ${h.ident.endianness}")
        appendLine("OS/ABI:       ${h.ident.osAbiName} (ABI version ${h.ident.abiVersion})")
        appendLine("Type:         ${h.typeName}")
        appendLine("Machine:      ${h.machineName}")
        ElfConstants.androidAbiFor(h.machine, h.is64)?.let { appendLine("Android ABI:  $it") }
        appendLine("Entry point:  ${h.entry.toHexAddr()}")
        appendLine("Flags:        ${h.flags.toHexAddr()}")
        appendLine("Program hdrs: ${h.phNum} @ ${h.phOff.toHexAddr()} (entsize ${h.phEntSize})")
        appendLine("Section hdrs: ${h.shNum} @ ${h.shOff.toHexAddr()} (entsize ${h.shEntSize}), names index ${h.shStrNdx}")
        elf.buildId?.let { appendLine("GNU Build ID: $it") }
        elf.soname?.let { appendLine("SONAME:       $it") }
        appendLine()
        appendLine("== PROGRAM HEADERS ==")
        appendLine("%-3s %-14s %-10s %-${w + 2}s %-10s %-10s %-4s %s".format("#", "Type", "Offset", "VirtAddr", "FileSiz", "MemSiz", "Flg", "Align"))
        elf.programHeaders.forEach { p ->
            appendLine("%-3d %-14s %-10s %-${w + 2}s %-10s %-10s %-4s %s".format(p.index, p.typeName, p.offset.toHexAddr(), p.vaddr.toHexAddr(w), p.fileSize.toHexAddr(), p.memSize.toHexAddr(), p.permissions, p.align.toHexAddr()))
        }
        appendLine()
        appendLine("== SECTIONS ==")
        if (elf.sections.isEmpty()) appendLine("(no section header table)")
        elf.sections.forEach { s ->
            appendLine("[%2d] %-24s %-14s addr=%s off=%s size=%s flags=%s align=%d".format(s.index, s.name, s.typeName, s.addr.toHexAddr(w), s.offset.toHexAddr(), s.size.toHexAddr(), s.flagsString, s.addrAlign))
        }
        appendLine()
        appendLine("== DYNAMIC SECTION ==")
        elf.dynamic.forEach { d -> appendLine("%-16s %s".format(d.tagName, d.stringValue?.let { "[$it]" } ?: d.value.toHexAddr())) }
        appendLine()
        appendLine("== DEPENDENCIES ==")
        if (elf.neededLibraries.isEmpty()) appendLine("(none)")
        elf.neededLibraries.forEach { appendLine("NEEDED  $it") }
        elf.rpath?.let { appendLine("RPATH   $it") }
        elf.runpath?.let { appendLine("RUNPATH $it") }
        elf.versionNeeds.forEach { appendLine("VERNEED ${it.file}: ${it.versions.joinToString()}") }
        if (elf.versionDefinitions.isNotEmpty()) appendLine("VERDEF  ${elf.versionDefinitions.joinToString()}")
        appendLine()
        appendLine("== HARDENING (facts derived from headers) ==")
        val sec = elf.security
        appendLine("RWX LOAD segment:    ${sec.hasRwxSegment}")
        appendLine("Non-exec stack:      ${sec.nxStack ?: "unknown (no PT_GNU_STACK)"}")
        appendLine("RELRO:               ${sec.relro}")
        appendLine("BIND_NOW:            ${sec.bindNow}")
        appendLine("Text relocations:    ${sec.hasTextRelocations}")
        appendLine("Max LOAD alignment:  ${sec.maxLoadAlignment} (${if (sec.supports16KbPages) "16 KiB page compatible" else "NOT 16 KiB page compatible"})")
        appendLine()
        appendLine("== SYMBOLS ==")
        appendLine("Dynamic: ${elf.dynamicSymbols.size}  Exported: ${elf.exportedSymbols.size}  Imported: ${elf.importedSymbols.size}  Static (.symtab): ${elf.staticSymbols.size}")
        elf.symbolAvailabilityNotes().forEach { appendLine("NOTE: $it") }
        elf.allSymbols.filter { it.name.isNotEmpty() }.forEach { s ->
            appendLine("%-6s %-${w + 2}s %8d %-6s %-7s %-9s %-5s %s".format(s.table, s.value.toHexAddr(w), s.size, s.typeName, s.bindName, s.visibilityName,
                s.sectionIndexName, s.displayName))
        }
        appendLine()
        appendLine("== RELOCATIONS (${elf.relocations.size}) ==")
        elf.relocations.forEach { rl ->
            appendLine("%-16s %-${w + 2}s %-26s %s%s".format(rl.sectionName, rl.offset.toHexAddr(w), rl.typeName, rl.symbolName ?: "", rl.addend?.let { " + ${it.toHexAddr()}" } ?: ""))
        }
        appendLine()
        appendLine("== NOTES ==")
        elf.notes.forEach { n -> appendLine("${n.sectionOrSegment}: owner=${n.owner} type=${n.typeName} desc=${n.descriptor.size} bytes") }
        appendLine()
        appendLine("== PARSER WARNINGS ==")
        if (elf.warnings.isEmpty()) appendLine("(none)")
        elf.warnings.forEach { appendLine("[${it.severity}] ${it.message}") }
    }

    fun toJson(elf: ElfFile, title: String, sha256: String?): String {
        val j = JsonWriter()
        val h = elf.header
        j.beginObject()
        j.field("tool", "Native Library RE Studio")
        j.field("file", title)
        j.field("sha256", sha256)
        j.field("fileSize", elf.fileSize)
        j.objectField("header")
            .field("class", "ELF${h.ident.elfClass.bits}").field("endianness", h.ident.endianness.name)
            .field("osAbi", h.ident.osAbiName).field("type", h.typeName).field("machine", h.machineName)
            .field("androidAbi", ElfConstants.androidAbiFor(h.machine, h.is64)).field("entry", h.entry.toHexAddr())
            .field("flags", h.flags.toHexAddr()).field("phnum", h.phNum).field("shnum", h.shNum)
            .field("buildId", elf.buildId).field("soname", elf.soname)
        j.endObject()
        j.arrayField("programHeaders")
        elf.programHeaders.forEach { p ->
            j.beginObject().field("type", p.typeName).field("offset", p.offset.toHexAddr()).field("vaddr", p.vaddr.toHexAddr())
                .field("fileSize", p.fileSize).field("memSize", p.memSize).field("flags", p.permissions).field("align", p.align).endObject()
        }
        j.endArray()
        j.arrayField("sections")
        elf.sections.forEach { s ->
            j.beginObject().field("index", s.index).field("name", s.name).field("type", s.typeName).field("flags", s.flagsString)
                .field("addr", s.addr.toHexAddr()).field("offset", s.offset.toHexAddr()).field("size", s.size).endObject()
        }
        j.endArray()
        j.arrayField("needed"); elf.neededLibraries.forEach { j.value(it) }; j.endArray()
        j.field("rpath", elf.rpath); j.field("runpath", elf.runpath)
        j.objectField("hardening")
            .field("rwxSegment", elf.security.hasRwxSegment).field("relro", elf.security.relro.name)
            .field("bindNow", elf.security.bindNow).field("textRelocations", elf.security.hasTextRelocations)
            .field("maxLoadAlignment", elf.security.maxLoadAlignment).field("supports16KbPages", elf.security.supports16KbPages)
        elf.security.nxStack?.let { j.field("nxStack", it) }
        j.endObject()
        j.field("stripped", elf.isStripped)
        j.arrayField("symbols")
        elf.allSymbols.filter { it.name.isNotEmpty() }.forEach { s ->
            j.beginObject().field("table", s.table.name).field("name", s.name).field("version", s.version)
                .field("value", s.value.toHexAddr()).field("size", s.size).field("type", s.typeName).field("bind", s.bindName)
                .field("visibility", s.visibilityName).field("undefined", s.isUndefined).endObject()
        }
        j.endArray()
        j.field("relocationCount", elf.relocations.size)
        j.arrayField("warnings"); elf.warnings.forEach { j.value("${it.severity}: ${it.message}") }; j.endArray()
        j.endObject()
        return j.toString()
    }
}
