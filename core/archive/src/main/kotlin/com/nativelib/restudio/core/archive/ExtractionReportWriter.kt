package com.nativelib.restudio.core.archive

import com.nativelib.restudio.core.common.JsonWriter
import com.nativelib.restudio.core.common.humanBytes

/** Deterministic TXT / JSON / CSV renderings of an [ExtractionReport] (duration is excluded for reproducibility). */
object ExtractionReportWriter {

    fun toText(r: ExtractionReport): String = buildString {
        appendLine("NATIVE LIBRARY EXTRACTION REPORT")
        appendLine("Generated by Native Library RE Studio (libraries were extracted, never loaded or executed)")
        appendLine()
        appendLine("Source:        ${r.sourceName}")
        appendLine("Type:          ${r.containerType.label}")
        appendLine("Size:          ${r.sourceSize} bytes (${humanBytes(r.sourceSize)})")
        appendLine("SHA-256:       ${r.sourceSha256}")
        appendLine("ZIP entries:   ${r.totalEntries}")
        if (r.nestedContainers.isNotEmpty()) appendLine("Nested APKs:   ${r.nestedContainers.joinToString()}")
        appendLine("ABIs found:    ${r.abis.ifEmpty { listOf("none") }.joinToString()}")
        appendLine("Libraries:     ${r.libraries.size} found, ${r.extractedCount} extracted, ${r.verifiedCount} verified (CRC-32 + SHA-256)")
        appendLine()
        for (abi in r.abis) {
            val list = r.librariesFor(abi)
            appendLine("== $abi (${list.size}) ==")
            list.forEach { appendLib(it) }
            appendLine()
        }
        val other = r.libraries.filter { it.entry.abi == null }
        if (other.isNotEmpty()) {
            appendLine("== Other shared objects (${other.size}) ==")
            other.forEach { appendLib(it) }
            appendLine()
        }
        appendLine("== ISSUES (${r.issues.size}) ==")
        if (r.issues.isEmpty()) appendLine("(none)")
        r.issues.forEach { appendLine("[${it.severity}] ${it.type.label}: ${it.message}${it.path?.let { p -> "  ($p)" } ?: ""}") }
    }

    private fun StringBuilder.appendLib(l: ExtractedLib) {
        val e = l.entry
        appendLine("- ${e.displayPath}")
        appendLine("    size=${e.size} compressed=${e.compressedSize} method=${e.method} crc=%08x".format(e.crc))
        appendLine("    sha256=${l.sha256 ?: "-"}  crcVerified=${l.crcVerified}  hashVerified=${l.hashVerified}")
        l.elf?.let { f ->
            appendLine("    ELF${f.bits} ${f.machine}  soname=${f.soname ?: "-"}  exports=${f.exportedCount} imports=${f.importedCount} stripped=${f.stripped} 16KiB=${f.supports16KbPages}")
            if (f.needed.isNotEmpty()) appendLine("    needs: ${f.needed.joinToString()}")
            f.buildId?.let { appendLine("    build-id: $it") }
        }
    }

    fun toJson(r: ExtractionReport): String {
        val j = JsonWriter()
        j.beginObject()
            .field("tool", "Native Library RE Studio").field("source", r.sourceName).field("type", r.containerType.name)
            .field("size", r.sourceSize).field("sha256", r.sourceSha256).field("zipEntries", r.totalEntries)
        j.arrayField("nestedContainers"); r.nestedContainers.forEach { j.value(it) }; j.endArray()
        j.arrayField("abis"); r.abis.forEach { j.value(it) }; j.endArray()
        j.arrayField("libraries")
        r.libraries.forEach { l ->
            j.beginObject().field("path", l.entry.displayPath).field("container", l.entry.container).field("abi", l.entry.abi)
                .field("fileName", l.entry.fileName).field("size", l.entry.size).field("compressedSize", l.entry.compressedSize)
                .field("method", l.entry.method.name).field("extractedTo", l.outputRelativePath).field("sha256", l.sha256)
                .field("crcVerified", l.crcVerified).field("hashVerified", l.hashVerified)
            l.elf?.let { f ->
                j.objectField("elf").field("machine", f.machine).field("bits", f.bits).field("elfAbi", f.elfAbi).field("soname", f.soname)
                    .field("exported", f.exportedCount).field("imported", f.importedCount).field("stripped", f.stripped)
                    .field("buildId", f.buildId).field("supports16KbPages", f.supports16KbPages)
                j.arrayField("needed"); f.needed.forEach { j.value(it) }; j.endArray()
                j.endObject()
            }
            j.endObject()
        }
        j.endArray()
        j.arrayField("issues")
        r.issues.forEach { j.beginObject().field("type", it.type.name).field("severity", it.severity.name).field("message", it.message).field("path", it.path).endObject() }
        j.endArray()
        j.endObject()
        return j.toString()
    }

    fun toCsv(r: ExtractionReport): String = buildString {
        appendLine("path,abi,size,compressed_size,method,sha256,crc_verified,hash_verified,machine,bits,soname,exports,imports,stripped,supports_16kb")
        r.libraries.forEach { l ->
            val f = l.elf
            appendLine(listOf(l.entry.displayPath, l.entry.abi ?: "", l.entry.size.toString(), l.entry.compressedSize.toString(), l.entry.method.name,
                l.sha256 ?: "", l.crcVerified.toString(), l.hashVerified.toString(), f?.machine ?: "", f?.bits?.toString() ?: "", f?.soname ?: "",
                f?.exportedCount?.toString() ?: "", f?.importedCount?.toString() ?: "", f?.stripped?.toString() ?: "", f?.supports16KbPages?.toString() ?: "",
            ).joinToString(",") { csv(it) })
        }
    }

    private fun csv(s: String) = if (s.any { it == ',' || it == '"' || it == '\n' }) "\"" + s.replace("\"", "\"\"") + "\"" else s
}
